CREATE TABLE IF NOT EXISTS iam_security_event (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_type VARCHAR(80) NOT NULL,
    actor VARCHAR(200),
    target VARCHAR(200),
    detail VARCHAR(1000),
    ip_address VARCHAR(64),
    user_agent VARCHAR(500),
    succeeded BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_iam_security_event_created_at ON iam_security_event(created_at DESC);
CREATE INDEX IF NOT EXISTS idx_iam_security_event_actor ON iam_security_event(actor);
CREATE TABLE IF NOT EXISTS iam_revoked_token (
    jti VARCHAR(200) PRIMARY KEY,
    expires_at TIMESTAMPTZ NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_iam_revoked_token_expires_at ON iam_revoked_token(expires_at);
CREATE TABLE IF NOT EXISTS iam_system_config (
    config_key VARCHAR(100) PRIMARY KEY,
    config_value VARCHAR(500) NOT NULL,
    updated_by VARCHAR(200) NOT NULL DEFAULT 'SYSTEM',
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
